export class ArcadeFont {
  /**
   * Draw pixel text horizontally
   * @param {CanvasRenderingContext2D} ctx
   * @param {string} text
   * @param {number} x
   * @param {number} y
   * @param {object} opts - { color, scale, align, slant, spacing, shadowColor }
   */
  static drawText(ctx, text, x, y, opts = {}) {
    const str = String(text).toUpperCase();
    const color = opts.color || '#FFFFFF';
    const scale = opts.scale || 2;
    const align = opts.align || 'left';
    const slant = opts.slant || 0; // italic slant per row (e.g. -0.35 for italic right)
    const charSpacing = opts.spacing !== undefined ? opts.spacing : 8 * scale;

    const totalWidth = str.length * charSpacing;
    let startX = x;
    if (align === 'center') startX = x - totalWidth / 2;
    else if (align === 'right') startX = x - totalWidth;

    if (opts.shadowColor) {
      this.drawText(ctx, str, x + scale, y + scale, {
        ...opts,
        color: opts.shadowColor,
        shadowColor: null
      });
    }

    ctx.fillStyle = color;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      const glyph = CHAR_MAP[ch] || CHAR_MAP[' '];
      const cx = startX + i * charSpacing;
      for (let row = 0; row < 8; row++) {
        const rowStr = glyph[row];
        const slantOffset = slant ? Math.round((7 - row) * slant * scale) : 0;
        for (let col = 0; col < 8; col++) {
          if (rowStr[col] === '#') {
            ctx.fillRect(
              Math.round(cx + col * scale + slantOffset),
              Math.round(y + row * scale),
              scale,
              scale
            );
          }
        }
      }
    }
  }

  /**
   * Draw vertical text rotated 90 deg CW (left edges) or 90 deg CCW (right edges)
   * matching Screenshot 2 "PRESS SHOOT BUTTON"
   */
  static drawVerticalText(ctx, text, x, y, direction = 'cw', opts = {}) {
    ctx.save();
    ctx.translate(x, y);
    if (direction === 'cw') {
      ctx.rotate(Math.PI / 2);
    } else {
      ctx.rotate(-Math.PI / 2);
    }
    this.drawText(ctx, text, 0, 0, { ...opts, align: opts.align || 'center' });
    ctx.restore();
  }
}
